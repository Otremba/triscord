// Generates src/icons.generated.ts from desktop/src/discord_icons.cpp, so the native client and the web UI
// share one list of icon paths (each recovered from Discord's bundle with REA; module ids are kept in the
// C++ comments). Run by tools/build.mjs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cpp = readFileSync(resolve(here, '../../src/discord_icons.cpp'), 'utf8');
const icons = {};
for (const m of cpp.matchAll(/case IconType::(\w+):\s*((?:\/\/[^\n]*\n\s*)*)return parseSvgPath\(((?:\s*"[^"]*")+)\s*\);/g)) {
  const [, name, comments, literals] = m;
  const d = [...literals.matchAll(/"([^"]*)"/g)].map(x => x[1]).join(' ');
  icons[name] = { d, source: comments.replace(/\/\/\s*/g, '').trim().replace(/\s+/g, ' ') };
}
const lines = ['// Generated by tools/icons-from-cpp.mjs from src/discord_icons.cpp. Do not edit.',
  'export type IconName = ' + Object.keys(icons).map(n => `'${n}'`).join(' | ') + ';',
  'export const ICON_PATHS: Record<IconName, string> = {'];
for (const [name, { d, source }] of Object.entries(icons)) lines.push(`  // ${source}`, `  ${name}: ${JSON.stringify(d)},`);
lines.push('};');
writeFileSync(resolve(here, '../src/icons.generated.ts'), lines.join('\n') + '\n');
console.log(`icons.generated.ts: ${Object.keys(icons).length} icons`);
