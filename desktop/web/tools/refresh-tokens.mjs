// Rewrites desktop/web/src/tokens.generated.css from the evidence extract-tokens.mjs left in desktop/out/web-tokens/
// (tokens.<theme>.json: every Discord token resolved by Chromium per theme, with provenance). Same output rule as
// extract-tokens.mjs step 4: only the tokens our CSS references. Use it when the CSS starts using a token that was
// recovered but not shipped yet; re-run extract-tokens.mjs itself when the Discord evidence changes.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const evidence = join(web, '..', 'out', 'web-tokens');
const THEMES = ['light', 'dark', 'darker', 'midnight'];
const resolved = Object.fromEntries(THEMES.map(t => [t, JSON.parse(readFileSync(join(evidence, `tokens.${t}.json`), 'utf8'))]));
// Values already shipped but absent from the evidence (kept as they are rather than dropped).
const shipped = {};
{
  const text = readFileSync(join(web, 'src', 'tokens.generated.css'), 'utf8');
  for (const block of text.matchAll(/:root\[data-theme="(\w+)"\] \{([^}]*)\}/g))
    shipped[block[1]] = Object.fromEntries([...block[2].matchAll(/(--[\w-]+): ([^;]+);/g)].map(m => [m[1], m[2]]));
}
const value = (theme, name) => resolved[theme][name]?.value ?? shipped[theme]?.[name];
const used = new Set();
const walk = dir => { for (const f of readdirSync(dir)) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else if (p.endsWith('.css') && !/generated\.css$/.test(p)) for (const m of readFileSync(p, 'utf8').matchAll(/var\((--[A-Za-z0-9_-]+)/g)) used.add(m[1]); } };
walk(join(web, 'src'));
const own = name => /^--tri-/.test(name) || /^--(custom-theme|background-gradient)/.test(name);   // ours / the colour theme's
const lines = ['/* Generated by tools/extract-tokens.mjs from Discord token declarations recovered with REA.',
  ' * Values computed by Chromium per theme; provenance in desktop/out/web-tokens/. Do not edit by hand. */'];
for (const theme of THEMES) {
  lines.push(`:root[data-theme="${theme}"] {`);
  for (const name of [...used].filter(n => value(theme, n)).sort()) lines.push(`  ${name}: ${value(theme, name)};`);
  lines.push('}');
}
writeFileSync(join(web, 'src', 'tokens.generated.css'), lines.join('\n') + '\n');
const missing = [...used].filter(n => !own(n) && !value('midnight', n));
console.log(`tokens.generated.css: ${[...used].filter(n => resolved.midnight[n]).length} tokens used by the UI`);
if (missing.length) console.log(`NOT FOUND in recovered tokens: ${missing.join(', ')}`);
