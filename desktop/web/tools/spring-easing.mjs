// Turns react-spring configs recovered from Discord's bundle into CSS: a linear() easing that samples the spring
// (same integration react-spring uses: damped harmonic motion from 0 to 1, rest when |v| and |x-1| fall under
// the precision) and its duration. Writes src/styles/motion.generated.css. Run by tools/build.mjs.
//   modal-in   module 150591 `l` {mass:1, tension:1000, friction:48}: modal opacity (64ms delay) and scrim __40128
//   tooltip    module 900002 `h` {tension:2400, friction:52}: tooltip opacity 0->1 and scale .95->1, same on leave
//   modal-out  module 150591 `o` {mass:1, tension:1200, friction:80}: modal opacity 0 and scale(0.9) on close
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const springs = {
  'modal-in': { mass: 1, tension: 1000, friction: 48, source: 'module 150591 (l / hP)' },
  'modal-out': { mass: 1, tension: 1200, friction: 80, source: 'module 150591 (o)' },
  'tooltip': { mass: 1, tension: 2400, friction: 52, source: 'module 900002 (h)' },
};

function sample({ mass, tension, friction }, precision = 0.001) {
  const dt = 1 / 1000; // seconds; fine step, sampled down below
  let x = 0, v = 0, t = 0;
  const points = [[0, 0]];
  while (t < 5) {
    const a = (-tension * (x - 1) - friction * v) / mass;
    v += a * dt; x += v * dt; t += dt;
    points.push([t, x]);
    if (Math.abs(v) < precision && Math.abs(1 - x) < precision) break;
  }
  return { duration: t, points };
}

const lines = ['/* Generated by tools/spring-easing.mjs from Discord\'s react-spring configs. Do not edit. */', ':root {'];
for (const [name, cfg] of Object.entries(springs)) {
  const { duration, points } = sample(cfg);
  const step = Math.max(1, Math.floor(points.length / 40));
  const stops = points.filter((_, i) => i % step === 0 || i === points.length - 1)
    .map(([t, x]) => `${x.toFixed(4)} ${(100 * t / duration).toFixed(2)}%`);
  stops[stops.length - 1] = `1 100%`;
  lines.push(`  /* ${cfg.source}: mass ${cfg.mass}, tension ${cfg.tension}, friction ${cfg.friction} */`);
  lines.push(`  --tri-spring-${name}-duration: ${Math.round(duration * 1000)}ms;`);
  lines.push(`  --tri-spring-${name}: linear(${stops.join(', ')});`);
}
lines.push('}', '');
const out = resolve(dirname(fileURLToPath(import.meta.url)), '../src/styles/motion.generated.css');
writeFileSync(out, lines.join('\n'));
console.log('motion.generated.css:', Object.keys(springs).join(', '));
